        <p class="text-[color:var(--muted)]">Departments raise requisitions. Buyers convert approved demand into RFQ, RFP, or RFI packages with specs, Incoterms, and deadlines.</p>
    </li>
    <li>
        <h2 class="font-display text-xl font-semibold">Discover and invite suppliers</h2>
        <p class="text-[color:var(--muted)]">Match by category, location, certification, and rating—or broadcast to the marketplace. Suppliers receive invitations and can ask questions.</p>
    </li>
    <li>
        <h2 class="font-display text-xl font-semibold">Compare, negotiate, award</h2>
        <p class="text-[color:var(--muted)]">Score bids, run reverse auctions, negotiate counter-offers, then award with contracts and e-signature-ready PDFs.</p>
    </li>
    <li>
        <h2 class="font-display text-xl font-semibold">Fulfill and pay</h2>
        <p class="text-[color:var(--muted)]">Issue POs, receive goods with QC, track shipments, match invoices, release escrow or wallet payouts, and capture reviews.</p>
    </li>
</ol>
