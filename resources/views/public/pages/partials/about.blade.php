<p class="lead">Procurement and Sourcing Marketplace is a modular B2B platform for the full buying cycle—from requisition and RFQ through bid, award, purchase order, delivery, invoice, and payment.</p>
<p>Built for manufacturers, hospitals, governments, traders, and NGOs, every capability ships as a module. Tenant admins enable only what their organization needs, so menus, routes, jobs, and dashboards stay clean.</p>
<ul>
    <li>Multi-tenant isolation with organization-scoped data and policies</li>
    <li>Buyer, supplier, logistics, and platform portals on Filament</li>
    <li>Unicode-ready PDFs, universal slugs, AI assistance, and catalog intelligence</li>
    <li>Demo-ready dataset so teams can evaluate the full RFQ-to-payment path</li>
